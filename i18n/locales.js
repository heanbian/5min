export const LOCALE_CODES = Object.freeze(Object.keys(LOCALES));
export const STORAGE_KEY = '5min.locale';
export const DEFAULT_LOCALE = 'en';

/** Map BCP 47 / browser tags onto a supported locale code. */
export function resolveLocale(tag) {
  if (!tag || typeof tag !== 'string') return null;
  const lower = tag.trim().replace(/_/g, '-');
  if (LOCALES[lower]) return lower;
  const base = lower.split('-')[0]?.toLowerCase();
  const region = lower.split('-')[1]?.toUpperCase();
  if (base === 'zh') {
    if (region === 'TW' || region === 'HK' || region === 'MO' || lower.includes('hant')) return 'zh-TW';
    return 'zh-CN';
  }
  if (base && LOCALES[base]) return base;
  return null;
}

export function detectLocale() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    const fromSaved = resolveLocale(saved);
    if (fromSaved) return fromSaved;
  } catch { /* private mode */ }

  const candidates = [
    ...(navigator.languages ?? []),
    navigator.language,
  ].filter(Boolean);

  for (const tag of candidates) {
    const hit = resolveLocale(tag);
    if (hit) return hit;
  }
  return DEFAULT_LOCALE;
}

export function t(locale, key, vars = {}) {
  const pack = LOCALES[locale] ?? LOCALES[DEFAULT_LOCALE];
  let text = pack[key] ?? LOCALES[DEFAULT_LOCALE][key] ?? key;
  for (const [k, v] of Object.entries(vars)) {
    text = text.replaceAll(`{${k}}`, String(v));
  }
  return text;
}
