function getLegalDoc(id) {
  const key = String(id || '').trim();
  return DOCS[key] || null;
}

function openLegal(docId) {
  const id = String(docId || '').trim();
  if (!DOCS[id]) return false;
  wx.navigateTo({
    url: `/pages/legal/legal?doc=${encodeURIComponent(id)}`,
    fail() {
      /* ignore */
    },
  });
  return true;
}

